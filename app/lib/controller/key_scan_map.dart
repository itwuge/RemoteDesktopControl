//
// 层级：controller（纯函数，无状态）
// 被谁调用：view/pages/session_page.dart 的键盘事件处理
// 依据：Flutter 的 PhysicalKeyboardKey 提供 USB HID usage（page 0x07），
//       被控端注入需要 PC/AT Set 1 扫描码（扩展键以 0xE0xx 表示）。
// 边界：只做映射；不判断权限、不发事件、不做限频（限频在 Rust 合并器）。
// ============================================================

import 'package:flutter/services.dart';

/// USB HID 键盘 usage page。
const int _hidPageKeyboard = 0x07;

/// HID usage（page 0x07）→ PC/AT Set 1 扫描码。
///
/// 字母区与数字区的映射不连续，按硬件规范逐一列出，不做算术推导。
