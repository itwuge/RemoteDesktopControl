  0xE2: 0x38, // Left Alt
  0xE3: 0xE05B, // Left Win
  0xE4: 0xE01D, // Right Ctrl
  0xE5: 0x36, // Right Shift
  0xE6: 0xE038, // Right Alt
  0xE7: 0xE05C, // Right Win
};

/// 物理键 → PC/AT Set 1 扫描码。
///
/// 参数 [key]：Flutter 的物理键。
/// 返回：扫描码（扩展键为 `0xE0xx`）；非键盘页或未收录的键返回 `null`。
int? scanCodeFor(PhysicalKeyboardKey key) {
  final usage = key.usbHidUsage;
  if ((usage >> 16) != _hidPageKeyboard) return null;
  return _scanCodeTable[usage & 0xFFFF];
}

/// 当前修饰键掩码（`1=Shift`、`2=Ctrl`、`4=Alt`、`8=Meta`）。
int currentModifierMask() {
  final keyboard = HardwareKeyboard.instance;
  var mask = 0;
  if (keyboard.isShiftPressed) mask |= 1;
  if (keyboard.isControlPressed) mask |= 2;
  if (keyboard.isAltPressed) mask |= 4;
  if (keyboard.isMetaPressed) mask |= 8;
  return mask;
}
