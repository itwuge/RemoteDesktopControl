  0x04: 0x1E, 0x05: 0x30, 0x06: 0x2E, 0x07: 0x20, 0x08: 0x12,
  0x09: 0x21, 0x0A: 0x22, 0x0B: 0x23, 0x0C: 0x17, 0x0D: 0x24,
  0x0E: 0x25, 0x0F: 0x26, 0x10: 0x32, 0x11: 0x31, 0x12: 0x18,
  0x13: 0x19, 0x14: 0x10, 0x15: 0x13, 0x16: 0x1F, 0x17: 0x14,
  0x18: 0x16, 0x19: 0x2F, 0x1A: 0x11, 0x1B: 0x2D, 0x1C: 0x15,
  0x1D: 0x2C,
  // 数字 1–0
  0x1E: 0x02, 0x1F: 0x03, 0x20: 0x04, 0x21: 0x05, 0x22: 0x06,
  0x23: 0x07, 0x24: 0x08, 0x25: 0x09, 0x26: 0x0A, 0x27: 0x0B,
  // 控制键
  0x28: 0x1C, // Enter
  0x29: 0x01, // Esc
  0x2A: 0x0E, // Backspace
  0x2B: 0x0F, // Tab
  0x2C: 0x39, // Space
  // 符号
  0x2D: 0x0C, 0x2E: 0x0D, 0x2F: 0x1A, 0x30: 0x1B,
  0x31: 0x2B, 0x33: 0x27, 0x34: 0x28, 0x35: 0x29,
  0x36: 0x33, 0x37: 0x34, 0x38: 0x35,
  0x39: 0x3A, // CapsLock
  // F1–F12
  0x3A: 0x3B, 0x3B: 0x3C, 0x3C: 0x3D, 0x3D: 0x3E,
  0x3E: 0x3F, 0x3F: 0x40, 0x40: 0x41, 0x41: 0x42,
  0x42: 0x43, 0x43: 0x44, 0x44: 0x57, 0x45: 0x58,
  // 编辑键（扩展）
  0x49: 0xE052, // Insert
  0x4A: 0xE047, // Home
  0x4B: 0xE049, // PageUp
  0x4C: 0xE053, // Delete
