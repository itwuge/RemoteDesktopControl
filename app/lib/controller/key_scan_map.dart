// 层级：controller（纯函数，无状态）
// 被谁调用：view/pages/session_page.dart 的键盘事件处理
// 依据：Flutter 的 PhysicalKeyboardKey 提供 USB HID usage（page 0x07），
//       被控端注入需要 PC/AT Set 1 扫描码（扩展键以 0xE0xx 表示）。
