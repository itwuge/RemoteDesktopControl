// =====** 环与内存池容量 =====**

/// 环 A（采集 → 编码）的 SPSC 容量，单位：帧。
///
/// 固定 3 帧：采集侧最多领先编码侧 3 帧，超出即丢帧，保证端到端时延有上界。
pub const RING_CAP_TO_ENC_CAP: usize = 3;

/// 帧内存池的块数。
///
/// 8 块覆盖「环 A 3 帧 + 编码在途 1 帧 + 重配过渡余量」的最坏瞬时占用，
/// 避免逐帧分配；池满时采集侧丢帧而不是等待。
pub const POOL_BLOCKS: usize = 8;
